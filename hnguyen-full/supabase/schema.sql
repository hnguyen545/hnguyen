-- HNGUYEN database schema for Supabase (run once in SQL Editor)
create table if not exists public.products (
  id text primary key,
  name text not null,
  description text not null default '',
  price bigint not null check (price >= 1000),
  category text not null default 'template',
  label text not null default 'PROJECT',
  demo_url text not null default '',
  file_path text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  code text not null unique,
  total bigint not null,
  status text not null default 'pending' check (status in ('pending','paid')),
  customer_name text not null default '',
  customer_email text not null default '',
  items_json jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  sepay_id text not null unique,
  order_code text not null references public.orders(code),
  amount bigint not null,
  content text not null default '',
  raw_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.support (
  id bigint generated by default as identity primary key,
  order_code text not null default '',
  message text not null,
  created_at timestamptz not null default now(),
  status text not null default 'new'
);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists support_created_at_idx on public.support(created_at desc);

-- All tables are private. Only the Netlify Function service-role key accesses them.
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.transactions enable row level security;
alter table public.support enable row level security;

