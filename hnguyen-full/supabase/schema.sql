-- Atomic, idempotent SePay processing: duplicate webhook IDs cannot pay twice.
create or replace function public.process_sepay_payment(
 p_sepay_id text, p_order_code text, p_amount bigint, p_content text,
 p_raw jsonb, p_account_number text, p_expected_account text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare o public.orders%rowtype; inserted_id bigint;
begin
  if exists(select 1 from public.transactions where sepay_id=p_sepay_id) then
    return jsonb_build_object('success',true,'duplicate',true);
  end if;
  select * into o from public.orders where code=p_order_code for update;
  if not found or o.status='paid' then
    return jsonb_build_object('success',true,'ignored','order missing or already paid');
  end if;
  if p_amount <> o.total then
    return jsonb_build_object('success',true,'ignored','amount mismatch');
  end if;
  if coalesce(p_expected_account,'')<>'' and coalesce(p_account_number,'')<>'' and p_expected_account<>p_account_number then
    return jsonb_build_object('success',true,'ignored','bank account mismatch');
  end if;
  insert into public.transactions(sepay_id,order_code,amount,content,raw_json)
  values(p_sepay_id,p_order_code,p_amount,coalesce(p_content,''),coalesce(p_raw,'{}'::jsonb))
  on conflict(sepay_id) do nothing returning id into inserted_id;
  if inserted_id is null then return jsonb_build_object('success',true,'duplicate',true); end if;
  update public.orders set status='paid',paid_at=now() where code=p_order_code and status='pending';
  return jsonb_build_object('success',true,'orderCode',p_order_code);
end; $$;
revoke all on function public.process_sepay_payment(text,text,bigint,text,jsonb,text,text) from public, anon, authenticated;
grant execute on function public.process_sepay_payment(text,text,bigint,text,jsonb,text,text) to service_role;

